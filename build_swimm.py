import argparse
import base64
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "api"))

import _core
from meetings import fetch_meetings

PAYLOAD_JSON = ROOT / "swimm-payload.json"
PAYLOAD_PY = ROOT / "api" / "_payload.py"


def write_payload_module(payload: dict) -> None:
    raw = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    b64 = base64.b64encode(raw).decode("ascii")
    lines = "\n".join(b64[i:i + 100] for i in range(0, len(b64), 100))
    PAYLOAD_PY.write_text(
        '"""\n'
        "_payload.py — GENERATED by build_swimm.py. Do not edit by hand.\n\n"
        "The dashboard payload, baked into the deployment so a signed-in user gets an\n"
        "instant page without waiting on Apollo. Base64 so no quoting can ever break\n"
        "this file. Not a route (leading underscore) and not statically served, so the\n"
        "only way to read it is through /api/feed, which requires a session cookie.\n\n"
        f"built: {payload.get('generated_at', '')}\n"
        '"""\n'
        "import base64\n"
        "import json\n\n"
        f'DATA_B64 = """\n{lines}\n"""\n\n\n'
        "def load():\n"
        "    return json.loads(base64.b64decode(DATA_B64))\n",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=30)
    ap.add_argument("--budget", type=float, default=None)
    args = ap.parse_args()

    payload = _core.build_payload(days=args.days, time_budget_s=args.budget)
    payload["meetings"] = fetch_meetings(payload.setdefault("errors", []))
    try:
        payload["former_sdrs"] = json.loads((ROOT / "former_sdrs.json").read_text(encoding="utf-8"))
    except Exception:
        payload["former_sdrs"] = []
    PAYLOAD_JSON.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    write_payload_module(payload)

    c = payload.get("_counts", {})
    print(f"generated_at {payload.get('generated_at')}")
    print(f"window {payload.get('date_min')} -> {payload.get('date_max')}")
    print(f"calls {c.get('calls')}  emails {c.get('emails')}  sdrs {c.get('sdrs')}  named {c.get('named')}")
    print(f"meetings {len(payload['meetings']) if payload.get('meetings') is not None else 'unavailable'}")
    print(f"call days {len({r['date'] for r in payload.get('calls_daily', [])})}")
    if c.get("unmapped_outcomes"):
        print(f"unmapped outcomes {c['unmapped_outcomes']}")
    for e in payload.get("errors", []):
        print(f"error: {e}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
